#!/usr/bin/env python3
"""gen_fixtures.py > pk_fixtures.h: RS256 / ES256 / EdDSA keys and live tokens for the CodSpeed benchmarks.

Runs bench/gen_pk_tokens.py (pyca/cryptography) and turns its output into a C header, so the benchmarks need no
Python, network or OpenSSL at build time. Keeps ES256, RS256-2048 and EdDSA, 16 tokens each (exp = 1_900_000_000).
Format the output with clang-format afterwards (scripts/lint.sh --fix)."""

import os
import subprocess
import sys

N = 16
here = os.path.dirname(os.path.abspath(__file__))
out = subprocess.run(
    [sys.executable, "-I", os.path.join(here, "..", "gen_pk_tokens.py"), str(N), "1"],
    check=True,
    capture_output=True,
    text=True,
).stdout.splitlines()

sets, cur = [], None
for line in out:
    kind, rest = line.split(" ", 1)
    if kind == "key":
        alg, k1, k2, _ = rest.split(" ")
        name = {"ES256": "es256", "EdDSA": "eddsa"}.get(alg, "rs256_%d" % (len(k1) * 4))
        cur = {"name": name, "k1": k1, "k2": k2, "tok": []}
        sets.append(cur)
    else:
        cur["tok"].append(rest)

print("/* pk_fixtures.h: generated by bench/codspeed/gen_fixtures.py; do not edit. */")
print("#pragma once")
print("#define PK_FIXTURE_N %d" % N)
for s in sets:
    if s["name"] == "rs256_3072":
        continue
    print('static const char *const %s_k1 = "%s";' % (s["name"], s["k1"]))
    print('static const char *const %s_k2 = "%s";' % (s["name"], s["k2"]))
    print("static const char *const %s_tok[PK_FIXTURE_N] = {" % s["name"])
    for t in s["tok"]:
        print('    "%s",' % t)
    print("};")
