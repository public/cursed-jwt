#!/usr/bin/env python3
"""gen-p256-table.py > crypto/src/cc_p256_table.inc

The fixed-base table for ES256 signing (crypto/src/cc_sign.c): j * 2^(4 i) * G for i = 0..64 and j = 1..8, in
Montgomery-affine form (x R mod p, y R mod p with R = 2^256), 4 little-endian 64-bit limbs per coordinate.  This is
the layout s2n-bignum's p256_scalarmulbase takes with blocksize 4 (entry (i, j) at 8 * (8 i + j - 1) words), and the
portable signer reads the same rows.  The table is public: G is the standard base point.  tests/test_sign.c
recomputes every entry with the library's own point arithmetic and compares.
"""

P = 2**256 - 2**224 + 2**192 + 2**96 - 1
A = P - 3
B = 0x5AC635D8AA3A93E7B3EBBD55769886BC651D06B0CC53B0F63BCE3C3E27D2604B
GX = 0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296
GY = 0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5
R = 2**256


def add(p1, p2):
    if p1 is None:
        return p2
    if p2 is None:
        return p1
    (x1, y1), (x2, y2) = p1, p2
    if x1 == x2:
        if (y1 + y2) % P == 0:
            return None
        lam = (3 * x1 * x1 + A) * pow(2 * y1, -1, P) % P
    else:
        lam = (y2 - y1) * pow(x2 - x1, -1, P) % P
    x3 = (lam * lam - x1 - x2) % P
    return (x3, (lam * (x1 - x3) - y1) % P)


def limbs(v):
    return ", ".join(f"0x{(v >> (64 * k)) & (2**64 - 1):016x}ull" for k in range(4))


def main():
    assert (GY * GY - (GX**3 + A * GX + B)) % P == 0
    print(
        "/* cc_p256_table.inc: generated by scripts/gen-p256-table.py, do not edit.  j 2^(4 i) G, i = 0..64, j = 1..8,"
    )
    print(
        " * Montgomery-affine (x R, y R mod p, R = 2^256), 4 little-endian limbs each: s2n-bignum's p256_scalarmulbase"
    )
    print(" * layout for blocksize 4.  Public data. */")
    print("// clang-format off")
    print("static const uint64_t CC_P256_GTAB[65 * 8 * 8] __attribute__((aligned(64))) = {")
    base = (GX, GY)
    for i in range(65):
        pt = None
        for j in range(1, 9):
            pt = add(pt, base)
            x, y = pt
            print(f"    {limbs(x * R % P)}, /* {i} {j} x */")
            print(f"    {limbs(y * R % P)}, /* y */")
        for _ in range(4):  # base *= 16
            base = add(base, base)
    print("};")
    print("// clang-format on")


if __name__ == "__main__":
    main()
